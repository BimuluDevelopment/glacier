import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { z } from 'zod';
import YAML from 'yaml';

const linux = process.platform === 'linux';
export const DEFAULT_CONFIG_PATH = linux ? '/etc/glacier/config.yml' : './config.yml';

// `.prefault({})` runs the empty object through the schema, so nested defaults apply.
const configSchema = z.object({
  debug: z.boolean().default(false),
  /** Node UUID, set by `glacierd pair`. */
  uuid: z.uuid(),
  /** Shared secret with the panel, set by `glacierd pair`. */
  token: z.string().min(32),
  panel: z.object({ url: z.url() }),
  api: z
    .object({
      host: z.string().default('0.0.0.0'),
      port: z.number().int().default(8080),
      /** Hostname browsers use to reach this node, from pairing. The installer gets its certificate for it. */
      fqdn: z.string().default(''),
      ssl: z
        .object({ enabled: z.boolean().default(false), cert: z.string().default(''), key: z.string().default('') })
        .prefault({}),
      /** MiB */
      uploadLimit: z.number().int().default(100),
      /** Extra browser origins allowed to open console websockets (the panel URL is always allowed). */
      allowedOrigins: z.array(z.string()).default([]),
    })
    .prefault({}),
  downloads: z
    .object({
      /** Hosts the panel may ask this node to download from (plugin/mod CDNs). "*.x" matches subdomains. */
      allowedHosts: z.array(z.string()).default(['cdn.modrinth.com', 'hangarcdn.papermc.io', '*.forgecdn.net']),
    })
    .prefault({}),
  sftp: z
    .object({
      port: z.number().int().default(2022),
      /** Generated on first start if missing. */
      hostKey: z.string().default(linux ? '/etc/glacier/sftp_host_key' : './sftp_host_key'),
      /** Lets admins turn SFTP off without touching the panel. */
      enabled: z.boolean().default(true),
    })
    .prefault({}),
  system: z
    .object({
      dataDirectory: z.string().default('/var/lib/glacier/volumes'),
      backupDirectory: z.string().default('/var/lib/glacier/backups'),
      tmpDirectory: z.string().default('/tmp/glacier'),
      logDirectory: z.string().default('/var/log/glacier'),
      /** The unprivileged user containers run as and that owns server files. */
      user: z.object({ uid: z.number().int().default(988), gid: z.number().int().default(988) }).prefault({}),
      timezone: z.string().default(Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC'),
      /** Seconds a graceful stop may take before the server is killed. */
      stopTimeout: z.number().int().default(60),
      /** Restart a server that crashes, unless it crashed again within this many seconds. 0 disables. */
      crashRestartCooldown: z.number().int().default(60),
    })
    .prefault({}),
  docker: z
    .object({
      /** Empty uses the platform default (unix socket or Windows named pipe). */
      socket: z.string().default(''),
      // Not 172.18.0.0/16: Docker Compose hands that range to the first project network on a host,
      // which would collide on machines that also run the panel's database through Compose.
      network: z
        .object({
          name: z.string().default('glacier0'),
          interface: z.string().default('172.30.0.1'),
          subnet: z.string().default('172.30.0.0/16'),
        })
        .prefault({}),
      dns: z.array(z.string()).default(['1.1.1.1', '1.0.0.1']),
      /** MiB of tmpfs mounted at /tmp in each container. */
      tmpfsSize: z.number().int().default(100),
      pidsLimit: z.number().int().default(512),
      installer: z.object({ memory: z.number().int().default(1024), cpu: z.number().int().default(100) }).prefault({}),
    })
    .prefault({}),
});

export type DaemonConfig = z.infer<typeof configSchema>;
export type DaemonConfigInput = z.input<typeof configSchema>;

export function parseConfig(input: unknown): DaemonConfig {
  return configSchema.parse(input);
}

export async function loadConfig(path: string): Promise<DaemonConfig> {
  let text: string;
  try {
    text = await readFile(path, 'utf8');
  } catch {
    throw new Error(`No config at ${path}. Pair this node first: glacierd pair --panel <url> --token <token>`);
  }
  const result = configSchema.safeParse(YAML.parse(text));
  if (!result.success) {
    const lines = result.error.issues.map((i) => `  ${i.path.join('.')}: ${i.message}`).join('\n');
    throw new Error(`Invalid config at ${path}:\n${lines}`);
  }
  return result.data;
}

export async function writeConfig(path: string, input: DaemonConfigInput): Promise<DaemonConfig> {
  const config = configSchema.parse(input);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, `# glacierd configuration. Generated by "glacierd pair"; safe to edit.\n${YAML.stringify(config)}`, {
    mode: 0o600,
  });
  return config;
}

export function panelOrigin(config: DaemonConfig) {
  return new URL(config.panel.url).origin;
}
